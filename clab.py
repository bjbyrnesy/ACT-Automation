from pathlib import Path

MARKER = "# Generated by ACT-Automation containerlab workflow\n"
NAME = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}$")
NODE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
IMAGE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:/@-]*$")
CONFIG_KEY = re.compile(r"^[A-Z][A-Z0-9_]*$")


def fail(message):
    raise ValueError(message)


def config_path():
    return Path.cwd() / ".config"


def read_config(path=None):
    """Load KEY=value pairs from local .config (same format as _common.sh)."""
    path = Path(path) if path is not None else config_path()
    if not path.is_file():
        return {}
    values = {}
    for line in path.read_text().splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, raw = stripped.partition("=")
        key = key.strip()
        if not CONFIG_KEY.fullmatch(key):
            continue
        try:
            parsed = shlex.split(raw, posix=True)
        except ValueError:
            fail(f"Invalid .config value for {key}")
        # Join tokens so multi-value keys (CLAB_DNS, CLAB_NTP) keep all IPs.
        values[key] = " ".join(parsed)
    return values


def config_image(config):
    if config.get("CLAB_IMAGE"):
        return config["CLAB_IMAGE"]
    version = config.get("EOS_VERSION")
    return f"ceos:{version}" if version else None


def config_ip_list(config, key, fallback=None):
    raw = (config.get(key) or "").strip()
    if not raw:
        return list(fallback or [])
    return raw.split()


def config_flag(value, default=False):
    if value is None or str(value).strip() == "":
        return default
    return str(value).strip().lower() in ("1", "y", "yes", "true", "on")


def parse_ipv4_list(addresses, label):
    try:
        return [str(ipaddress.IPv4Address(address)) for address in addresses]
    except ipaddress.AddressValueError as exc:
        fail(f"Invalid {label} address: {exc}")


def _b64url_decode(segment):
    padding = "=" * (-len(segment) % 4)
    return base64.urlsafe_b64decode(segment + padding)


def validate_enrollment_token(token):
    """Reject expired JWTs and service/user account tokens used for API auth.

    TerminAttr token-secure needs a Device Registration enrollment token.
    Account tokens (dst=account) reach CVaaS and fail with Invalid token.
    """
    parts = token.split(".")
    if len(parts) != 3 or not all(parts):
        fail(
            "CVaaS token must be a JWT from Devices → Device Registration → "
            "Generate a Token."
        )
    try:
        payload = json.loads(_b64url_decode(parts[1]))
    except (ValueError, json.JSONDecodeError):
        fail("CVaaS token payload is not valid base64 JSON (truncated/corrupted).")
    if not isinstance(payload, dict):
        fail("CVaaS token payload must be a JSON object.")
    if payload.get("dst") == "account":
        fail(
            "CVAAS_TOKEN is a user/service-account API token (dst=account), not a "
            "device enrollment token. Generate one in CVaaS: Devices → Device "
            "Registration → Generate a Token, then set CVAAS_TOKEN in .config."
        )
    exp = payload.get("exp")
    if exp is not None:
        try:
            exp_i = int(exp)
        except (TypeError, ValueError):
            fail("CVaaS token has an invalid exp claim.")
        if exp_i <= int(time.time()):
            fail(
                "CVaaS enrollment token is expired. Generate a new one: Devices → "
                "Device Registration → Generate a Token."
            )
    return payload


MGMT_VRF = "MGMT"


def mgmt_service_commands(name_servers, ntp_servers, mgmt_vrf=None):
    """Build EOS DNS/NTP lines. With mgmt_vrf, create VRF and bind servers to it."""
    lines = []
    if mgmt_vrf:
        lines.append(f"vrf instance {mgmt_vrf}")
        lines.extend(
            f"ip name-server vrf {mgmt_vrf} {address}" for address in name_servers
        )
        lines.extend(f"ntp server vrf {mgmt_vrf} {address}" for address in ntp_servers)
    else:
        lines.extend(f"ip name-server {address}" for address in name_servers)
        lines.extend(f"ntp server {address}" for address in ntp_servers)
    return lines


def read_yaml(path):
    try:
        result = subprocess.run(
            ["yq", "-o=json", ".", str(path)],
            check=True,
            capture_output=True,
            text=True,
        )
        return json.loads(result.stdout)
    except FileNotFoundError:
        fail("yq is required; install Mike Farah yq (v4).")
    except (subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        fail(f"Cannot read YAML {path}: {exc}")


def validate_lab(path):
    if not path.read_text().startswith(MARKER):
        fail("Only containerlab files generated by this project are supported.")
    lab = read_yaml(path)
    name = lab.get("name", "")
    nodes = lab.get("topology", {}).get("nodes", {})
    if (
        not isinstance(name, str)
        or not NAME.fullmatch(name)
        or not isinstance(nodes, dict)
        or not nodes
    ):
        fail("Invalid lab name or node list.")
    for name_, node in nodes.items():
        if (
            not isinstance(name_, str)
            or not NODE.fullmatch(name_)
            or not isinstance(node, dict)
            or node.get("kind") != "arista_ceos"
        ):
            fail("Invalid or non-cEOS node in generated lab.")
    return lab


def validate_network_name(name):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", name):
        fail("Invalid Docker management network name.")
    return name


def act_hostname(act_name):
    """EOS/CVaaS hostname: ACT node name with only a leading ``clab-`` removed."""
    name = act_name[5:] if act_name.startswith("clab-") else act_name
    if not name or not NODE.fullmatch(name):
        fail(f"Invalid ACT hostname: {act_name}")
    return name


def short_node_name(act_name, lab_name=None):
    """Drop redundant prefixes so containerlab names stay short.

    Strips a leading ``clab-`` (ACT hostname habit). If the name still starts
    with ``<lab>-`` and the remainder looks like a site node (``A-leaf1`` /
    ``bb1``), strip the lab prefix too — e.g. ACT ``blz-B-leaf2`` with
    ``--name blz`` → node ``B-leaf2`` → container ``clab-blz-B-leaf2``.
    EOS hostname stays ``blz-B-leaf2`` via ``CLAB_HOSTNAME`` / generate exec.
    """
    name = act_hostname(act_name)
    if lab_name and name.startswith(f"{lab_name}-"):
        candidate = name[len(lab_name) + 1 :]
        if re.match(r"(?:[A-Z]-|bb)", candidate or ""):
            name = candidate
    if not name or not NODE.fullmatch(name):
        fail(f"Invalid node name after shortening: {act_name}")
    return name


def inventory_hostname(lab_name, node_name, node_data=None):
    """Restore lab-prefixed EOS hostname from a short containerlab node key."""
    env = node_data.get("env") if isinstance(node_data, dict) else None
    if isinstance(env, dict):
        configured = env.get("CLAB_HOSTNAME")
        if configured:
            if not NODE.fullmatch(configured):
                fail(f"Invalid CLAB_HOSTNAME for {node_name}: {configured}")
            return configured
    if lab_name and re.match(r"(?:[A-Z]-|bb)", node_name or ""):
        return f"{lab_name}-{node_name}"
    return node_name


def topology_layout(names, links=()):
    """Lay out fabric roles, grouping member leaves beneath their uplinks."""
    rows = {"bb": 0, "border": 180, "spine": 360, "leaf": 540, "mleaf": 720}
    groups, roles = {}, {}
    for name in names:
        match = re.search(
            r"(?:^|-)(?:([A-D])-)?(bb|border|spine|leaf|mleaf)([0-9]+)$", name
        )
        if not match:
            continue
        site, role, number = match.groups()
        group = "core" if role == "bb" else f"site {site or 'A'}"
        groups.setdefault(group, {}).setdefault(role, []).append((int(number), name))
        roles[name] = (group, role)

    parents = {}
    for link in links:
        endpoints = link.get("connection", [])
        if len(endpoints) != 2:
            continue
        left, right = (str(endpoint).split(":", 1)[0] for endpoint in endpoints)
        for child, parent in ((left, right), (right, left)):
            if (roles.get(child, (None, None))[1] == "mleaf"
                and roles.get(parent, (None, None))[1] == "leaf"
                and roles[child][0] == roles[parent][0]):
                parents.setdefault(child, set()).add(parent)

    labels = {}
    sites = sorted(group for group in groups if group != "core")
    cursor = 0
    for group in sites:
        role_nodes = groups[group]
        leaves = [name for _, name in sorted(role_nodes.get("leaf", []))]
        members = [name for _, name in sorted(role_nodes.get("mleaf", []))]
        remaining = list(leaves)
        segments = []
        while remaining:
            leaf = remaining[0]
            connected = next((parents[member] for member in members
                              if leaf in parents.get(member, set())
                              and parents[member].issubset(set(remaining))), None)
            selected = [item for item in remaining if item in connected] if connected else remaining[:2]
            for item in selected:
                remaining.remove(item)
            children = [member for member in members if parents.get(member) and parents[member].issubset(set(selected))]
            segments.append((selected, children, max(320, 200 + max(0, len(children) - 1) * 140)))
        loose = [member for member in members if not parents.get(member)]
        leaf_width = sum(segment[2] for segment in segments)
        width = max(320, leaf_width, len(loose) * 160,
                    *(len(items) * 160 for role, items in role_nodes.items() if role not in ("leaf", "mleaf")))
        center = cursor + width // 2
        for role, items in role_nodes.items():
            if role in ("leaf", "mleaf"):
                continue
            for index, (_, name) in enumerate(sorted(items)):
                x = center + (2 * index - len(items) + 1) * 80
                labels[name] = {"graph-group": group, "graph-posX": str(x), "graph-posY": str(rows[role])}
        segment_cursor = center - leaf_width // 2
        for segment_leaves, children, segment_width in segments:
            midpoint = segment_cursor + segment_width // 2
            for index, name in enumerate(segment_leaves):
                x = midpoint + (2 * index - len(segment_leaves) + 1) * 80
                labels[name] = {"graph-group": group, "graph-posX": str(x), "graph-posY": str(rows["leaf"])}
            for index, name in enumerate(children):
                x = midpoint + (2 * index - len(children) + 1) * 70
                labels[name] = {"graph-group": group, "graph-posX": str(x), "graph-posY": str(rows["mleaf"])}
            segment_cursor += segment_width
        for index, name in enumerate(loose):
            x = center + (2 * index - len(loose) + 1) * 80
            labels[name] = {"graph-group": group, "graph-posX": str(x), "graph-posY": str(rows["mleaf"])}
        cursor += width + 240
    if "core" in groups:
        core = sorted(groups["core"]["bb"])
        center = max(0, cursor - 240) // 2
        for index, (_, name) in enumerate(core):
            x = center + (2 * index - len(core) + 1) * 80
            labels[name] = {"graph-group": "core", "graph-posX": str(x), "graph-posY": "0"}
    return labels


def viewer_annotations(layout, node_names):
    """Create explicit Topology Viewer group boxes and node memberships."""
    annotations = {"freeTextAnnotations": [], "freeShapeAnnotations": [],
                   "trafficRateAnnotations": [], "scriptButtonAnnotations": [],
                   "groupStyleAnnotations": [], "networkNodeAnnotations": [],
                   "nodeAnnotations": [], "edgeAnnotations": [],
                   "aliasEndpointAnnotations": [], "viewerSettings": {}}
    groups = {}
    for name, labels in sorted(layout.items()):
        group = labels["graph-group"]
        point = {"x": int(labels["graph-posX"]), "y": int(labels["graph-posY"])}
        groups.setdefault(group, []).append(point)
        annotations["nodeAnnotations"].append({"id": node_names[name], "position": point,
                                               "level": "1", "groupId": f"{group}:1"})
    for group, points in sorted(groups.items()):
        xmin, xmax = min(p["x"] for p in points), max(p["x"] for p in points)
        ymin, ymax = min(p["y"] for p in points), max(p["y"] for p in points)
        annotations["groupStyleAnnotations"].append({
            "id": f"{group}:1", "name": group, "level": "1",
            "position": {"x": xmin - 100, "y": ymin - 75},
            "width": xmax - xmin + 200, "height": ymax - ymin + 150,
            "backgroundColor": "#d9d9d9", "backgroundOpacity": 20,
            "borderColor": "#dddddd", "borderWidth": 0.5,
            "borderStyle": "solid", "borderRadius": 0, "zIndex": -1,
        })
    return annotations


def generate(args):
    if not args.name:
        fail("Lab name required (--name or CLAB_NAME in .config).")
    if not args.image:
        fail("Image required (--image, CLAB_IMAGE, or EOS_VERSION in .config).")
    if not NAME.fullmatch(args.name):
        fail(
            "Lab name must be lowercase letters, numbers and hyphens, starting with a letter or number (maximum 63 characters)."
        )
    if not IMAGE.fullmatch(args.image):
        fail("Invalid image name.")
    try:
        subnet = ipaddress.ip_network(args.mgmt_subnet, strict=True)
        if "/" not in args.mgmt_subnet or subnet.version != 4 or subnet.prefixlen > 30:
            raise ValueError("expected an IPv4 network with a prefix of /30 or shorter")
    except ValueError as exc:
        fail(f"Invalid management subnet: {exc}")
    name_servers = parse_ipv4_list(args.name_servers, "name-server")
    ntp_servers = parse_ipv4_list(args.ntp_servers or [], "ntp-server")
    source = Path(args.source)
    if "Generated by generate.sh" not in source.read_text()[:2048]:
        fail("Input must be an ACT topology generated by generate.sh.")
    act = read_yaml(source)
    nodes, links = {}, []
    act_to_short = {}
    for entry in act.get("nodes", []):
        if not isinstance(entry, dict) or len(entry) != 1:
            fail("Invalid ACT node.")
        name, data = next(iter(entry.items()))
        if (
            not NODE.fullmatch(name)
            or not isinstance(data, dict)
            or data.get("node_type") != "veos"
            or not data.get("serial_number")
        ):
            fail(f"Invalid vEOS node: {name}")
        hostname = act_hostname(name)
        short = short_node_name(name, lab_name=args.name)
        if short in nodes:
            fail(
                f"Node name collision after shortening prefixes: {name} and another node both map to {short}"
            )
        act_to_short[name] = short
        serial = (
            "CLAB"
            + hashlib.sha256(str(data["serial_number"]).encode())
            .hexdigest()[:12]
            .upper()
        )
        hostname_exec = "Cli -p 15 -c " + shlex.quote(
            "\n".join(
                [
                    "enable",
                    "configure terminal",
                    f"hostname {hostname}",
                    "end",
                    "write memory",
                ]
            )
        )
        nodes[short] = {
            "kind": "arista_ceos",
            "image": args.image,
            "env": {
                "CEOS_SERIAL_NUMBER": serial,
                "CLAB_MGMT_VRF": MGMT_VRF,
                "CLAB_HOSTNAME": hostname,
            },
            "exec": [hostname_exec],
        }
    if not nodes:
        fail("Topology contains no vEOS nodes.")
    used = set()
    for link in act.get("links", []):
        endpoints = link.get("connection", [])
        if not isinstance(endpoints, list) or len(endpoints) != 2:
            fail("Invalid ACT link.")
        converted = []
        for endpoint in endpoints:
            match = re.fullmatch(r"([^:]+):Ethernet([1-9][0-9]*)", str(endpoint))
            if not match or match.group(1) not in act_to_short:
                fail(f"Invalid link endpoint: {endpoint}")
            converted.append(f"{act_to_short[match.group(1)]}:eth{match.group(2)}")
        if any(e in used for e in converted) or converted[0] == converted[1]:
            fail("An interface is used by more than one link.")
        used.update(converted)
        links.append({"endpoints": converted})
    layout = topology_layout(act_to_short, act.get("links", []))
    for act_name, labels in layout.items():
        nodes[act_to_short[act_name]]["labels"] = labels
    # Generated nodes always use MGMT VRF — DNS/NTP must be VRF-scoped.
    bootstrap = (
        ["enable", "configure terminal"]
        + mgmt_service_commands(name_servers, ntp_servers, mgmt_vrf=MGMT_VRF)
        + ["end", "write memory"]
    )
    bootstrap_exec = "Cli -p 15 -c " + shlex.quote("\n".join(bootstrap))
    lab = {
        "name": args.name,
        "mgmt": {"ipv4-subnet": str(subnet)},
        "topology": {
            "kinds": {"arista_ceos": {"exec": [bootstrap_exec]}},
            "nodes": nodes,
            "links": links,
        },
    }
    if args.mgmt_network:
        lab["mgmt"]["network"] = validate_network_name(args.mgmt_network)
    output = Path(args.output or f"{args.name}.clab.yml")
    output.write_text(MARKER + json.dumps(lab, indent=2) + "\n")
    annotations_path = Path(str(output) + ".annotations.json")
    if annotations_path.exists():
        print(f"Preserving existing viewer annotations: {annotations_path}")
    else:
        annotations_path.write_text(json.dumps(viewer_annotations(layout, act_to_short), indent=2) + "\n")
        print(f"Wrote {annotations_path}")
    print(f"Wrote {output}")
    print(
        "cEOS serial persistence depends on image support for CEOS_SERIAL_NUMBER; verify it on your host."
    )



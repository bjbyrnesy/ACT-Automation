#!/usr/bin/env python3
"""Generate, deploy and onboard containerlab labs derived from ACT topologies."""
import argparse
import base64
import getpass
import hashlib
import ipaddress
import json
import re
import shlex
import subprocess
import sys
from pathlib import Path

MARKER = '# Generated by ACT-Automation containerlab workflow\n'
NAME = re.compile(r'^[a-z0-9][a-z0-9-]{0,62}$')
NODE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_.-]*$')
IMAGE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9._:/@-]*$')


def fail(message):
    raise ValueError(message)


def read_yaml(path):
    try:
        result = subprocess.run(['yq', '-o=json', '.', str(path)], check=True,
                                capture_output=True, text=True)
        return json.loads(result.stdout)
    except FileNotFoundError:
        fail('yq is required; install Mike Farah yq (v4).')
    except (subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        fail(f'Cannot read YAML {path}: {exc}')


def validate_lab(path):
    if not path.read_text().startswith(MARKER):
        fail('Only containerlab files generated by this project are supported.')
    lab = read_yaml(path)
    name = lab.get('name', '')
    nodes = lab.get('topology', {}).get('nodes', {})
    if not isinstance(name, str) or not NAME.fullmatch(name) or not isinstance(nodes, dict) or not nodes:
        fail('Invalid lab name or node list.')
    for name_, node in nodes.items():
        if not isinstance(name_, str) or not NODE.fullmatch(name_) or not isinstance(node, dict) or node.get('kind') != 'arista_ceos':
            fail('Invalid or non-cEOS node in generated lab.')
    return lab


def validate_network_name(name):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', name):
        fail('Invalid Docker management network name.')
    return name


def generate(args):
    if not NAME.fullmatch(args.name):
        fail('Lab name must be lowercase letters, numbers and hyphens, starting with a letter or number (maximum 63 characters).')
    if not IMAGE.fullmatch(args.image):
        fail('Invalid image name.')
    try:
        subnet = ipaddress.ip_network(args.mgmt_subnet, strict=True)
        if '/' not in args.mgmt_subnet or subnet.version != 4 or subnet.prefixlen > 30:
            raise ValueError('expected an IPv4 network with a prefix of /30 or shorter')
    except ValueError as exc:
        fail(f'Invalid management subnet: {exc}')
    try:
        name_servers = [str(ipaddress.IPv4Address(address)) for address in args.name_servers]
    except ipaddress.AddressValueError as exc:
        fail(f'Invalid name-server address: {exc}')
    source = Path(args.source)
    if 'Generated by generate.sh' not in source.read_text()[:2048]:
        fail('Input must be an ACT topology generated by generate.sh.')
    act = read_yaml(source)
    nodes, links = {}, []
    for entry in act.get('nodes', []):
        if not isinstance(entry, dict) or len(entry) != 1:
            fail('Invalid ACT node.')
        name, data = next(iter(entry.items()))
        if not NODE.fullmatch(name) or not isinstance(data, dict) or data.get('node_type') != 'veos' or not data.get('serial_number'):
            fail(f'Invalid vEOS node: {name}')
        serial = 'CLAB' + hashlib.sha256(str(data['serial_number']).encode()).hexdigest()[:12].upper()
        nodes[name] = {'kind': 'arista_ceos', 'image': args.image, 'env': {'CEOS_SERIAL_NUMBER': serial, 'CLAB_MGMT_VRF': 'MGMT'}}
    if not nodes:
        fail('Topology contains no vEOS nodes.')
    used = set()
    for link in act.get('links', []):
        endpoints = link.get('connection', [])
        if not isinstance(endpoints, list) or len(endpoints) != 2:
            fail('Invalid ACT link.')
        converted = []
        for endpoint in endpoints:
            match = re.fullmatch(r'([^:]+):Ethernet([1-9][0-9]*)', str(endpoint))
            if not match or match.group(1) not in nodes:
                fail(f'Invalid link endpoint: {endpoint}')
            converted.append(f'{match.group(1)}:eth{match.group(2)}')
        if any(e in used for e in converted) or converted[0] == converted[1]:
            fail('An interface is used by more than one link.')
        used.update(converted)
        links.append({'endpoints': converted})
    dns_commands = ['enable', 'configure terminal']
    dns_commands.extend(f'ip name-server vrf MGMT {address}' for address in name_servers)
    dns_commands.extend(['end', 'write memory'])
    dns_exec = 'Cli -p 15 -c ' + shlex.quote('; '.join(dns_commands))
    lab = {'name': args.name, 'mgmt': {'ipv4-subnet': str(subnet)},
           'topology': {'kinds': {'arista_ceos': {'exec': [dns_exec]}},
                        'nodes': nodes, 'links': links}}
    if args.mgmt_network:
        lab['mgmt']['network'] = validate_network_name(args.mgmt_network)
    output = Path(args.output or f'{args.name}.clab.yml')
    output.write_text(MARKER + json.dumps(lab, indent=2) + '\n')
    print(f'Wrote {output}')
    print('cEOS serial persistence depends on image support for CEOS_SERIAL_NUMBER; verify it on your host.')


DEPLOY_SCRIPT = r'''set -eu
name=$1
dir="$HOME/.act-automation/clab/$name"
mkdir -p "$dir"
(umask 077; cat > "$dir/topology.clab.yml")
if [ "$(id -u)" -eq 0 ]; then
  containerlab deploy -t "$dir/topology.clab.yml"
else
  sudo -n containerlab deploy -t "$dir/topology.clab.yml"
fi
'''
DOCKER_LIST_SCRIPT = r'''set -eu
if docker info >/dev/null 2>&1; then
  exec docker ps --format '{{.Names}}'
else
  exec sudo -n docker ps --format '{{.Names}}'
fi
'''
DOCKER_SCRIPT = r'''set -eu
if docker info >/dev/null 2>&1; then
  exec docker exec -i "$1" Cli -p 15
else
  exec sudo -n docker exec -i "$1" Cli -p 15
fi
'''


def host_run(host, script, args, data):
    command = ['bash', '-c', script, 'clab-workflow', *args]
    if host:
        if host.startswith('-') or not re.fullmatch(r'[A-Za-z0-9_.@:-]+', host):
            fail('Invalid SSH host; use an SSH alias or user@hostname.')
        command = ['ssh', '-o', 'BatchMode=yes', '--', host, shlex.join(command)]
    return subprocess.run(command, input=data, text=True, capture_output=True)


def deploy(args):
    path = Path(args.topology)
    lab = validate_lab(path)
    content = path.read_text()
    if args.mgmt_network:
        network = validate_network_name(args.mgmt_network)
        mgmt = lab.setdefault('mgmt', {})
        if not isinstance(mgmt, dict):
            fail('Invalid management network configuration.')
        mgmt['network'] = network
        content = MARKER + json.dumps(lab, indent=2) + '\n'
    result = host_run(args.host, DEPLOY_SCRIPT, [lab['name']], content)
    if result.stdout:
        print(result.stdout, end='')
    if result.returncode:
        fail(f'Deployment failed: {result.stderr.strip()}')
    if result.stderr:
        print(result.stderr, end='', file=sys.stderr)
    print(f"Deployed {lab['name']}.")


def check_onboarding_host(host, lab):
    result = host_run(host, DOCKER_LIST_SCRIPT, [], '')
    if result.returncode:
        detail = result.stderr.strip() or 'Docker is unavailable.'
        hint = ' Use --host user@lab-host if your lab runs remotely.' if not host else ''
        fail(f'Cannot inspect Docker on {host or "the local machine"}: {detail}.{hint}')
    running = set(result.stdout.splitlines())
    expected = {f"clab-{lab['name']}-{node}" for node in lab['topology']['nodes']}
    if not running.intersection(expected):
        hint = ' Use --host user@lab-host if your lab runs remotely.' if not host else ''
        fail(f"No running containers for lab {lab['name']} found on {host or 'the local machine'}.{hint}")


def onboard(args):
    lab = validate_lab(Path(args.topology))
    check_onboarding_host(args.host, lab)
    endpoint = args.endpoint or input('CVaaS host (for example apiserver.arista.io): ').strip()
    if not re.fullmatch(r'[A-Za-z0-9.-]+', endpoint):
        fail('Invalid CVaaS host.')
    token = getpass.getpass('CVaaS enrollment token: ').strip()
    if not token or '\n' in token or '\r' in token:
        fail('Enrollment token cannot be empty or contain newlines.')
    encoded = base64.b64encode(token.encode()).decode()
    commands = (f'enable\nbash echo {encoded} > /tmp/cv-onboarding-token.b64\n'
                'bash base64 -d /tmp/cv-onboarding-token.b64 > /tmp/cv-onboarding-token\n'
                'bash rm -f /tmp/cv-onboarding-token.b64\n'
                f'configure\ndaemon TerminAttr\n   exec /usr/bin/TerminAttr -smashexcludes=ale,flexCounter,hardware,kni,pulse,strata -cvaddr={endpoint}:443 -cvauth=token-secure,/tmp/cv-onboarding-token -taillogs\n'
                '   shutdown\n   no shutdown\nend\nwrite\n')
    print(f"Onboarding {len(lab['topology']['nodes'])} cEOS node(s) in {lab['name']} to {endpoint}.")
    if input('Continue? [y/N] ').strip().lower() not in ('y', 'yes'):
        print('Aborted.')
        return
    failures = []
    for node in lab['topology']['nodes']:
        container = f"clab-{lab['name']}-{node}"
        env = lab['topology']['nodes'][node].get('env', {})
        vrf_flag = ' -cvvrf=MGMT' if isinstance(env, dict) and env.get('CLAB_MGMT_VRF') == 'MGMT' else ''
        node_commands = commands.replace(' -taillogs', vrf_flag + ' -taillogs')
        result = host_run(args.host, DOCKER_SCRIPT, [container], node_commands)
        if result.returncode or re.search(r'(?im)^\s*%\s*(?:error|invalid|incomplete|ambiguous)', result.stdout):
            failures.append(node)
            detail = result.stderr.strip().replace(token, '[redacted]').replace(encoded, '[redacted]')
            if not detail:
                errors = [line.strip() for line in result.stdout.splitlines() if re.match(r'(?i)^\s*%\s*(?:error|invalid|incomplete|ambiguous)', line)]
                detail = '; '.join(errors).replace(token, '[redacted]').replace(encoded, '[redacted]')
            print(f'  {node}: failed' + (f' ({detail})' if detail else ' (check container and EOS readiness)'), file=sys.stderr)
        else:
            print(f'  {node}: configuration submitted')
    if failures:
        fail('Onboarding failed for: ' + ', '.join(failures))
    print('Configuration submitted. Check CVaaS inventory to confirm registration.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    gen = sub.add_parser('generate', help='Convert a generate.sh ACT topology to containerlab YAML')
    gen.add_argument('source')
    gen.add_argument('--name', required=True)
    gen.add_argument('--image', required=True)
    gen.add_argument('--output')
    gen.add_argument('--mgmt-subnet', default='172.100.100.0/22',
                     help='IPv4 management subnet (default: 172.100.100.0/22)')
    gen.add_argument('--mgmt-network', help='Docker management network name (default: clab)')
    gen.add_argument('--name-servers', nargs='+', default=['8.8.8.8', '1.1.1.1'], metavar='IP',
                     help='IPv4 name servers for MGMT (default: 8.8.8.8 1.1.1.1)')
    gen.set_defaults(func=generate)
    for command, handler in [('deploy', deploy), ('onboard', onboard)]:
        action = sub.add_parser(command)
        action.add_argument('topology')
        action.add_argument('--host', help='SSH alias or user@host; omit to run locally')
        if command == 'deploy':
            action.add_argument('--mgmt-network', help='Use this Docker management network for this deployment')
        if command == 'onboard':
            action.add_argument('--endpoint', help='CVaaS hostname (default: prompt)')
        action.set_defaults(func=handler)
    args = parser.parse_args()
    try:
        args.func(args)
    except (ValueError, OSError) as exc:
        print(f'ERROR: {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())

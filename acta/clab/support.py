def mgmt_service_commands(name_servers, ntp_servers, mgmt_vrf=None):
    """Build EOS DNS/NTP lines. With mgmt_vrf, create VRF and bind servers to it."""
    lines = []
    if mgmt_vrf:
        lines.append(f"vrf instance {mgmt_vrf}")
        lines.extend(
            f"ip name-server vrf {mgmt_vrf} {address}" for address in name_servers
        )
        lines.extend(f"ntp server vrf {mgmt_vrf} {address}" for address in ntp_servers)
    else:
        lines.extend(f"ip name-server {address}" for address in name_servers)
        lines.extend(f"ntp server {address}" for address in ntp_servers)
    return lines


def read_yaml(path):
    try:
        result = subprocess.run(
            ["yq", "-o=json", ".", str(path)],
            check=True,
            capture_output=True,
            text=True,
        )
        return json.loads(result.stdout)
    except FileNotFoundError:
        fail("yq is required; install Mike Farah yq (v4).")
    except (subprocess.CalledProcessError, json.JSONDecodeError) as exc:
        fail(f"Cannot read YAML {path}: {exc}")


def is_project_clab_lab(path: Path) -> bool:
    """Return True when ``path`` is a lab YAML this project generated."""
    return Path(path).read_text(encoding="utf-8").startswith(MARKER)


def is_act_topology(path: Path) -> bool:
    """Return True when ``path`` looks like an ``acta.py act create`` topology."""
    header = Path(path).read_text(encoding="utf-8")[:2048]
    return "Generated by acta." in header or "Generated by generate.sh" in header


_ACT_NODE_NAME_RE = re.compile(r"^  - (?P<name>[^:\n]+):", re.MULTILINE)
_ACT_ROLE_SUFFIX_RE = re.compile(
    r"^(.+?)-(?:[A-D]-)?(?:border|spine|leaf|mleaf|bb)\d+$",
    re.IGNORECASE,
)
_DATE_SUFFIX_RE = re.compile(r"-\d{4}-\d{2}-\d{2}$")


def lab_name_from_act_path(path: Path) -> str:
    """Derive a containerlab-safe name from an ACT topology filename."""
    stem = Path(path).stem.casefold()
    if stem.startswith("topology-"):
        stem = stem.removeprefix("topology-")
    stem = _DATE_SUFFIX_RE.sub("", stem)
    cleaned = re.sub(r"[^a-z0-9-]+", "-", stem).strip("-")
    if not cleaned or not NAME.fullmatch(cleaned):
        fail(
            "Could not derive a valid lab name from the topology filename; "
            "set CLAB_NAME in .config or pass --name."
        )
    return cleaned


def hostname_prefix_from_act(path: Path) -> str | None:
    """Return the shared hostname prefix from ACT node names (e.g. ``blz2``)."""
    prefixes: set[str] = set()
    for match in _ACT_NODE_NAME_RE.finditer(Path(path).read_text(encoding="utf-8")):
        role_match = _ACT_ROLE_SUFFIX_RE.fullmatch(match.group("name").strip())
        if role_match is None:
            continue
        prefixes.add(role_match.group(1).casefold())
    if len(prefixes) != 1:
        return None
    prefix = next(iter(prefixes))
    return prefix if NAME.fullmatch(prefix) else None


def resolve_clab_lab_name(source: Path, args) -> str:
    """Pick lab name: explicit ``--name``, else topology prefix, else config/path.

    Topology hostname prefix wins over a stale ``CLAB_NAME`` that does not match
    this fabric (e.g. config ``blz`` vs nodes ``blz2-A-spine1``).
    """
    explicit = getattr(args, "name", None) or None
    if explicit:
        return explicit
    derived = hostname_prefix_from_act(source)
    if derived:
        return derived
    config = getattr(args, "config", None) or {}
    cached = config.get("CLAB_NAME") or None
    if cached and NAME.fullmatch(cached):
        return cached
    return lab_name_from_act_path(source)


def materialize_clab_from_act(source: Path, args) -> Path:
    """Generate a sibling ``*.clab.yml`` from an ACT topology and return it."""
    from .generate import generate

    config = getattr(args, "config", None) or {}
    name = resolve_clab_lab_name(source, args)
    image = getattr(args, "image", None) or config_image(config)
    output = source.with_name(f"{source.stem}.clab.yml")
    generate_args = argparse_namespace(
        source=str(source),
        name=name,
        image=image,
        host_image=config.get("CLAB_HOST_IMAGE") or DEFAULT_HOST_IMAGE,
        config=config,
        output=str(output),
        mgmt_subnet=config.get("CLAB_MGMT_SUBNET") or "172.100.100.0/22",
        mgmt_gateway=config.get("CLAB_MGMT_GATEWAY") or None,
        mgmt_range=config.get("CLAB_MGMT_RANGE") or None,
        mgmt_bridge=config.get("CLAB_MGMT_BRIDGE") or None,
        mgmt_mtu=_optional_int(config.get("CLAB_MGMT_MTU")),
        mgmt_network=(
            getattr(args, "mgmt_network", None)
            or config.get("CLAB_MGMT_NETWORK")
            or None
        ),
        name_servers=config_ip_list(config, "CLAB_DNS", ["8.8.8.8", "1.1.1.1"]),
        ntp_servers=config_ip_list(config, "CLAB_NTP"),
    )
    generate(generate_args)
    return output


def argparse_namespace(**kwargs):
    """Build a lightweight namespace for ``generate`` without importing argparse."""

    class _Namespace:
        pass

    namespace = _Namespace()
    for key, value in kwargs.items():
        setattr(namespace, key, value)
    return namespace


def _optional_int(raw):
    if raw is None or str(raw).strip() == "":
        return None
    return int(raw)


def resolve_existing_clab_sibling(path: Path, args) -> Path | None:
    """Find an already-generated sibling ``.clab.yml`` for an ACT topology."""
    path = Path(path)
    candidates = [
        path.with_name(f"{path.stem}.clab.yml"),
        path.with_suffix(".clab.yml"),
    ]
    name = resolve_clab_lab_name(path, args)
    candidates.append(path.with_name(f"{name}.clab.yml"))
    seen: set[Path] = set()
    for candidate in candidates:
        key = candidate.resolve() if candidate.exists() else candidate
        if key in seen:
            continue
        seen.add(key)
        if candidate.is_file() and is_project_clab_lab(candidate):
            return candidate
    return None


def resolve_topology_path(path: Path, args, *, materialize: bool = True) -> Path:
    """Return a project clab lab path, auto-converting ACT YAML when enabled.

    When ``materialize`` is False (destroy), require an existing sibling
    ``.clab.yml`` instead of regenerating and overwriting local edits.
    """
    path = Path(path)
    if is_project_clab_lab(path):
        return path
    from_act = getattr(args, "from_act", None)
    if from_act is None:
        config = getattr(args, "config", None) or {}
        from_act = config_flag(config.get("CLAB_FROM_ACT"), default=False)
    if from_act:
        if not is_act_topology(path):
            fail(
                f"{path} is not an ACT topology from acta.py act create; "
                "cannot use --from-act / CLAB_FROM_ACT."
            )
        if not materialize:
            existing = resolve_existing_clab_sibling(path, args)
            if existing is not None:
                return existing
            fail(
                f"No existing .clab.yml sibling for {path.name}; "
                "run clab generate/deploy first (destroy will not regenerate)."
            )
        return materialize_clab_from_act(path, args)
    if is_act_topology(path):
        fail(
            "That looks like an ACT topology. Pass --from-act (or set "
            "CLAB_FROM_ACT=y in .config) to convert and continue, or run "
            "acta.py clab generate first."
        )
    fail("Only containerlab files generated by this project are supported.")


def validate_lab(path):
    if not Path(path).read_text(encoding="utf-8").startswith(MARKER):
        fail("Only containerlab files generated by this project are supported.")
    lab = read_yaml(path)
    name = lab.get("name", "")
    nodes = lab.get("topology", {}).get("nodes", {})
    if (
        not isinstance(name, str)
        or not NAME.fullmatch(name)
        or not isinstance(nodes, dict)
        or not nodes
    ):
        fail("Invalid lab name or node list.")
    for name_, node in nodes.items():
        if (
            not isinstance(name_, str)
            or not NODE.fullmatch(name_)
            or not isinstance(node, dict)
        ):
            fail("Invalid node in generated lab.")
        kind = node.get("kind")
        if kind == "arista_ceos":
            continue
        if kind == "linux" and node.get("image"):
            continue
        fail("Invalid or unsupported node kind in generated lab.")
    return lab


def validate_network_name(name):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", name):
        fail("Invalid Docker management network name.")
    return name


def act_hostname(act_name):
    """EOS/CVaaS hostname: ACT node name with only a leading ``clab-`` removed."""
    name = act_name.removeprefix("clab-")
    if not name or not NODE.fullmatch(name):
        fail(f"Invalid ACT hostname: {act_name}")
    return name


def short_node_name(act_name, lab_name=None):
    """Legacy short node key helper (kept for callers/tests).

    Generate now keeps full ACT hostnames as node keys with ``prefix: ""``.
    This still strips a leading ``clab-`` and optional ``<lab>-`` site/bb
    prefix when callers need the old shortened form.
    """
    name = act_hostname(act_name)
    if lab_name and name.startswith(f"{lab_name}-"):
        candidate = name[len(lab_name) + 1 :]
        if re.match(r"(?:[A-Z]-|bb)", candidate or ""):
            name = candidate
    if not name or not NODE.fullmatch(name):
        fail(f"Invalid node name after shortening: {act_name}")
    return name


def inventory_hostname(lab_name, node_name, node_data=None):
    """Restore lab-prefixed EOS hostname from a short containerlab node key."""
    env = node_data.get("env") if isinstance(node_data, dict) else None
    if isinstance(env, dict):
        configured = env.get("CLAB_HOSTNAME")
        if configured:
            if not NODE.fullmatch(configured):
                fail(f"Invalid CLAB_HOSTNAME for {node_name}: {configured}")
            return configured
    if lab_name and re.match(r"(?:[A-Z]-|bb)", node_name or ""):
        return f"{lab_name}-{node_name}"
    return node_name


def container_name(lab, node_name):
    """Return the runtime container name for a node in ``lab``.

    Honors topology ``prefix`` (default ``clab``). Empty prefix means the
    container name is exactly the node key.
    """
    if not isinstance(lab, dict):
        fail("Invalid lab definition.")
    prefix = lab.get("prefix", "clab")
    if prefix is None:
        prefix = "clab"
    lab_name = lab.get("name") or ""
    if prefix == "":
        return node_name
    if prefix == "__lab-name":
        return f"{lab_name}-{node_name}"
    return f"{prefix}-{lab_name}-{node_name}"


def support_bundle(root, lab):
    nodes = lab["topology"]["nodes"]
    # Only cEOS (startup-config) nodes need SN identity files — skip linux hosts.
    ceos_nodes = {
        name: node for name, node in nodes.items() if node.get("startup-config")
    }
    if not ceos_nodes:
        return None
    root = Path(root).resolve()
    paths = ["configs/base-config.eos"]
    for name, node in ceos_nodes.items():
        binds = node.get("binds", [])
        legacy = "configs/SN/__clabNodeName__.txt:/mnt/flash/ceos-config:ro"
        extension = "txt" if legacy in binds else "eos"
        paths.append(f"configs/SN/{name}.{extension}")
    stream = io.BytesIO()
    with tarfile.open(fileobj=stream, mode="w:gz") as archive:
        for path in paths:
            source = root / path
            if not source.is_file() or not source.resolve().is_relative_to(root):
                fail(f"Missing or unsafe required support file: {source}")
            content = source.read_bytes()
            entry = tarfile.TarInfo(path)
            entry.mode = 0o600
            entry.size = len(content)
            archive.addfile(entry, io.BytesIO(content))
    return base64.b64encode(stream.getvalue()).decode()



def host_run(host, script, args, data):
    command = ["bash", "-c", script, "clab-workflow", *args]
    if host:
        if host.startswith("-") or not re.fullmatch(r"[A-Za-z0-9_.@:-]+", host):
            fail("Invalid SSH host; use an SSH alias or user@hostname.")
        command = ["ssh", "-o", "BatchMode=yes", "--", host, shlex.join(command)]
    return subprocess.run(
        command, input=data, text=True, capture_output=True, check=False
    )

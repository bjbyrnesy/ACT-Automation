    def test_onboard_reports_partial_failure_without_leaking_token(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / 'lab.yml'
            path.write_text(clab.MARKER + json.dumps({'name': 'demo', 'topology': {'nodes': {'a': {'kind': 'arista_ceos'}, 'b': {'kind': 'arista_ceos'}}}}))
            args = clab.argparse.Namespace(topology=str(path), host='labhost', endpoint='www.arista.io')
            calls = []
            def host(host, script, argv, data):
                calls.append((host, argv, data))
                return subprocess.CompletedProcess([], 0 if len(calls) == 1 else 1, '', '')
            with mock.patch.object(clab, 'check_onboarding_host'), mock.patch.object(clab, 'host_run', side_effect=host), mock.patch.object(clab.getpass, 'getpass', return_value='secret-token'), mock.patch('builtins.input', return_value='y'):
                with self.assertRaisesRegex(ValueError, 'Onboarding failed for: b'):
                    clab.onboard(args)
            self.assertEqual([c[1][0] for c in calls], ['clab-demo-a', 'clab-demo-b'])
            self.assertNotIn('secret-token', repr([c[1] for c in calls]))
            self.assertNotIn('secret-token', calls[0][2])
            self.assertIn('-cvaddr=www.arista.io:443', calls[0][2])

    def test_onboarding_uses_mgmt_vrf_only_for_nodes_configured_with_it(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / 'lab.yml'
            nodes = {'new': {'kind': 'arista_ceos', 'env': {'CLAB_MGMT_VRF': 'MGMT'}},
                     'old': {'kind': 'arista_ceos'}}
            path.write_text(clab.MARKER + json.dumps({'name': 'demo', 'topology': {'nodes': nodes}}))
            args = clab.argparse.Namespace(topology=str(path), host=None, endpoint='apiserver.arista.io')
            with mock.patch.object(clab, 'check_onboarding_host'), mock.patch.object(clab, 'host_run', return_value=subprocess.CompletedProcess([], 0, '', '')) as run, mock.patch.object(clab.getpass, 'getpass', return_value='token'), mock.patch('builtins.input', return_value='y'):
                clab.onboard(args)
            self.assertIn('-cvvrf=MGMT', run.call_args_list[0].args[3])
            self.assertNotIn('-cvvrf=MGMT', run.call_args_list[1].args[3])


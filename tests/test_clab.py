def _b64url(data):
    return base64.urlsafe_b64encode(json.dumps(data).encode()).rstrip(b"=").decode()


def enrollment_jwt(**claims):
    payload = {"exp": int(time.time()) + 3600}
    payload.update(claims)
    return f"{_b64url({'alg': 'none', 'typ': 'JWT'})}.{_b64url(payload)}.sig"



import json
import os
import subprocess
import shutil
import tempfile
import unittest
import importlib.util
from unittest import mock

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("clab", ROOT / "clab.py")
clab = importlib.util.module_from_spec(spec)
spec.loader.exec_module(clab)

class ContainerlabTests(unittest.TestCase):
    def test_convert_preserves_nodes_and_links_and_separates_identity(self):
        with tempfile.TemporaryDirectory() as d:
            source = Path(d) / 'act.yml'
            source.write_text('''# Generated by generate.sh\nveos:\n  version: 4.35.4M\nnodes:\n  - demo-spine1:\n      node_type: veos\n      serial_number: demo-spine1\n  - demo-leaf1:\n      node_type: veos\n      serial_number: demo-leaf1\nlinks:\n  - connection: [demo-spine1:Ethernet1, demo-leaf1:Ethernet1]\n''')
            out = Path(d) / 'lab.clab.yml'
            cmd = ['python3', str(ROOT / 'clab.py'), 'generate', str(source), '--name', 'demo', '--image', 'ceos:latest', '--output', str(out)]
            result = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            lab = json.loads(subprocess.check_output(['yq', '-o=json', '.', str(out)], text=True))
            self.assertEqual(set(lab['topology']['nodes']), {'demo-spine1', 'demo-leaf1'})
            self.assertEqual(lab['topology']['links'][0]['endpoints'], ['demo-spine1:eth1', 'demo-leaf1:eth1'])
            node = lab['topology']['nodes']['demo-spine1']
            self.assertEqual(node['kind'], 'arista_ceos')
            self.assertNotEqual(node['env']['CEOS_SERIAL_NUMBER'], 'demo-spine1')
            first = out.read_text()
            self.assertEqual(subprocess.run(cmd, capture_output=True).returncode, 0)
            self.assertEqual(out.read_text(), first)

    def test_real_generator_topologies_convert_with_all_links(self):
        cases = [
            ('demo\n\n1\n2\n4\ny\ny\n1\n1\ny\n\ny\n', 'single'),
            ('demo\n\n2\n2\n4\ny\ny\n1\n1\ny\ny\n\ny\n', 'multi'),
        ]
        for answers, name in cases:
            with self.subTest(name=name), tempfile.TemporaryDirectory() as d:
                for file in ('generate.sh', '_common.sh'):
                    shutil.copy(ROOT / file, d)
                result = subprocess.run(['bash', str(Path(d) / 'generate.sh')], input=answers, capture_output=True, text=True, timeout=30)
                self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
                source = next(Path(d).glob('topology-*.yml'))
                output = Path(d) / 'out.yml'
                convert = subprocess.run(['python3', str(ROOT / 'clab.py'), 'generate', str(source), '--name', name, '--image', 'ceos:latest', '--output', str(output)], capture_output=True, text=True)
                self.assertEqual(convert.returncode, 0, convert.stderr)
                act = clab.read_yaml(source)
                lab = clab.read_yaml(output)
                self.assertEqual(len(lab['topology']['nodes']), len(act['nodes']))
                self.assertEqual(len(lab['topology']['links']), len(act['links']))

    def test_rejects_reused_interfaces(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / 'source.yml'
            path.write_text("""# Generated by generate.sh
nodes:
  - a: {node_type: veos, serial_number: a}
  - b: {node_type: veos, serial_number: b}
links:
  - connection: [a:Ethernet1, b:Ethernet1]
  - connection: [a:Ethernet1, b:Ethernet2]
""")
            result = subprocess.run(['python3', str(ROOT / 'clab.py'), 'generate', str(path), '--name', 'lab', '--image', 'ceos:latest', '--output', str(Path(d) / 'out.yml')], capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn('more than one link', result.stderr)

    def test_onboard_reports_partial_failure_without_leaking_token(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / 'lab.yml'
            path.write_text(clab.MARKER + json.dumps({'name': 'demo', 'topology': {'nodes': {'a': {'kind': 'arista_ceos'}, 'b': {'kind': 'arista_ceos'}}}}))
            args = clab.argparse.Namespace(topology=str(path), host='labhost', endpoint='www.arista.io')
            calls = []
            def host(host, script, argv, data):
                calls.append((host, argv, data))
                return subprocess.CompletedProcess([], 0 if len(calls) == 1 else 1, '', '')
            with mock.patch.object(clab, 'host_run', side_effect=host), mock.patch.object(clab.getpass, 'getpass', return_value='secret-token'), mock.patch('builtins.input', return_value='y'):
                with self.assertRaisesRegex(ValueError, 'Onboarding failed for: b'):
                    clab.onboard(args)
            self.assertEqual([c[1][0] for c in calls], ['clab-demo-a', 'clab-demo-b'])
            self.assertNotIn('secret-token', repr([c[1] for c in calls]))
            self.assertNotIn('secret-token', calls[0][2])
            self.assertIn('-cvaddr=www.arista.io:443', calls[0][2])

    def test_local_deployment_stores_topology_on_host(self):
        with tempfile.TemporaryDirectory() as d:
            directory = Path(d)
            fake = directory / 'sudo'
            fake.write_text('#!/bin/sh\nprintf "%s\\n" "$*" > "$HOME/invocation"\n')
            fake.chmod(0o755)
            with mock.patch.dict(os.environ, {'HOME': d, 'PATH': d + os.pathsep + os.environ['PATH']}):
                result = clab.host_run(None, clab.DEPLOY_SCRIPT, ['demo'], 'example topology')
            self.assertEqual(result.returncode, 0, result.stderr)
            saved = directory / '.act-automation/clab/demo/topology.clab.yml'
            self.assertEqual(saved.read_text(), 'example topology')
            self.assertIn('containerlab deploy -t', (directory / 'invocation').read_text())

    def test_remote_host_command_keeps_payload_on_stdin(self):
        with mock.patch.object(clab.subprocess, 'run', return_value=subprocess.CompletedProcess([], 0, '', '')) as run:
            clab.host_run('user@host', clab.DOCKER_SCRIPT, ['clab-demo-a'], 'sensitive-data')
        args, kwargs = run.call_args
        self.assertEqual(args[0][0], 'ssh')
        self.assertNotIn('sensitive-data', repr(args[0]))
        self.assertEqual(kwargs['input'], 'sensitive-data')

    def test_rejects_unmanaged_lab(self):
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / 'lab.yml'
            path.write_text('name: demo\n')
            with self.assertRaisesRegex(ValueError, 'generated by this project'):
                clab.validate_lab(path)

if __name__ == '__main__':
    unittest.main()

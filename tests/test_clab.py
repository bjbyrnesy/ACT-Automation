    def test_convert_preserves_nodes_and_links_and_separates_identity(self):
        with tempfile.TemporaryDirectory() as d:
            source = Path(d) / "act.yml"
            source.write_text(
                """# Generated by generate.sh\nveos:\n  version: 4.35.4M\nnodes:\n  - demo-spine1:\n      node_type: veos\n      serial_number: demo-spine1\n  - demo-leaf1:\n      node_type: veos\n      serial_number: demo-leaf1\nlinks:\n  - connection: [demo-spine1:Ethernet1, demo-leaf1:Ethernet1]\n"""
            )
            out = Path(d) / "lab.clab.yml"
            cmd = [
                "python3",
                str(ROOT / "acta.py"),
                "clab",
                "generate",
                str(source),
                "--name",
                "demo",
                "--image",
                "ceos:latest",
                "--output",
                str(out),
                "--name-servers",
                "8.8.8.8",
                "1.1.1.1",
                "--ntp-servers",
            ]
            result = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            lab = json.loads(
                subprocess.check_output(["yq", "-o=json", ".", str(out)], text=True)
            )
            self.assertEqual(lab["mgmt"]["ipv4-subnet"], "172.100.100.0/22")
            command = lab["topology"]["kinds"]["arista_ceos"]["exec"][0]
            self.assertIn("vrf instance MGMT", command)
            self.assertIn("ip name-server vrf MGMT 8.8.8.8", command)
            self.assertIn("ip name-server vrf MGMT 1.1.1.1", command)
            args = shlex.split(command)
            self.assertEqual(args[:4], ["Cli", "-p", "15", "-c"])
            self.assertEqual(
                args[4].splitlines(),
                [
                    "enable",
                    "configure terminal",
                    "vrf instance MGMT",
                    "ip name-server vrf MGMT 8.8.8.8",
                    "ip name-server vrf MGMT 1.1.1.1",
                    "end",
                    "write memory",
                ],
            )
            self.assertEqual(
                set(lab["topology"]["nodes"]), {"demo-spine1", "demo-leaf1"}
            )
            self.assertEqual(
                lab["topology"]["links"][0]["endpoints"],
                ["demo-spine1:et1", "demo-leaf1:et1"],
            )
            node = lab["topology"]["nodes"]["demo-spine1"]
            self.assertEqual(node["kind"], "arista_ceos")
            self.assertEqual(node["env"]["CLAB_MGMT_VRF"], "MGMT")
            self.assertTrue(
                any(
                    "ip name-server vrf MGMT 8.8.8.8" in command
                    for command in node["exec"]
                )
            )
            self.assertNotEqual(node["env"]["CEOS_SERIAL_NUMBER"], "demo-spine1")
            first = out.read_text()
            self.assertEqual(subprocess.run(cmd, capture_output=True).returncode, 0)

    def test_local_deployment_stores_topology_on_host(self):
        with tempfile.TemporaryDirectory() as d:
            directory = Path(d)
            fake = directory / 'sudo'
            fake.write_text('#!/bin/sh\nprintf "%s\\n" "$*" > "$HOME/invocation"\n')
            fake.chmod(0o755)
            with mock.patch.dict(os.environ, {'HOME': d, 'PATH': d + os.pathsep + os.environ['PATH']}):
                result = clab.host_run(None, clab.DEPLOY_SCRIPT, ['demo'], 'example topology')
            self.assertEqual(result.returncode, 0, result.stderr)
            saved = directory / '.act-automation/clab/demo/topology.clab.yml'
            self.assertEqual(saved.read_text(), 'example topology')
            self.assertIn('containerlab deploy -t', (directory / 'invocation').read_text())

    def test_deployment_does_not_force_private_umask_on_containerlab(self):
        with tempfile.TemporaryDirectory() as d:
            fake = Path(d) / 'sudo'
            fake.write_text('#!/bin/sh\numask > "$HOME/containerlab-umask"\n')
            fake.chmod(0o755)
            previous = os.umask(0o022)
            try:
                with mock.patch.dict(os.environ, {'HOME': d, 'PATH': d + os.pathsep + os.environ['PATH']}):
                    result = clab.host_run(None, clab.DEPLOY_SCRIPT, ['demo'], 'topology')
            finally:
                os.umask(previous)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(int((Path(d) / 'containerlab-umask').read_text().strip(), 8), 0o022)
            topology = Path(d) / '.act-automation/clab/demo/topology.clab.yml'
            self.assertEqual(topology.stat().st_mode & 0o777, 0o600)


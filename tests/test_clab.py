class ContainerlabTests(unittest.TestCase):
    def test_convert_preserves_nodes_and_links_and_separates_identity(self):
        with tempfile.TemporaryDirectory() as d:
            source = Path(d) / 'act.yml'
            source.write_text('''# Generated by generate.sh\nveos:\n  version: 4.35.4M\nnodes:\n  - demo-spine1:\n      node_type: veos\n      serial_number: demo-spine1\n  - demo-leaf1:\n      node_type: veos\n      serial_number: demo-leaf1\nlinks:\n  - connection: [demo-spine1:Ethernet1, demo-leaf1:Ethernet1]\n''')
            out = Path(d) / 'lab.clab.yml'
            cmd = ['python3', str(ROOT / 'clab.py'), 'generate', str(source), '--name', 'demo', '--image', 'ceos:latest', '--output', str(out)]
            result = subprocess.run(cmd, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            lab = json.loads(subprocess.check_output(['yq', '-o=json', '.', str(out)], text=True))
            self.assertEqual(lab['mgmt']['ipv4-subnet'], '172.100.100.0/22')
            command = lab['topology']['kinds']['arista_ceos']['exec'][0]
            self.assertIn('ip name-server vrf MGMT 8.8.8.8', command)
            self.assertIn('ip name-server vrf MGMT 1.1.1.1', command)
            self.assertIn('write memory', command)
            self.assertEqual(set(lab['topology']['nodes']), {'demo-spine1', 'demo-leaf1'})
            self.assertEqual(lab['topology']['links'][0]['endpoints'], ['demo-spine1:eth1', 'demo-leaf1:eth1'])
            node = lab['topology']['nodes']['demo-spine1']
            self.assertEqual(node['kind'], 'arista_ceos')
            self.assertEqual(node['env']['CLAB_MGMT_VRF'], 'MGMT')
            self.assertNotEqual(node['env']['CEOS_SERIAL_NUMBER'], 'demo-spine1')
            first = out.read_text()
            self.assertEqual(subprocess.run(cmd, capture_output=True).returncode, 0)
            self.assertEqual(out.read_text(), first)

    def test_custom_management_subnet_and_invalid_subnet(self):
        with tempfile.TemporaryDirectory() as d:
            source = Path(d) / 'act.yml'
            source.write_text('# Generated by generate.sh\nnodes:\n  - a: {node_type: veos, serial_number: a}\nlinks: []\n')
            output = Path(d) / 'lab.yml'
            command = ['python3', str(ROOT / 'clab.py'), 'generate', str(source), '--name', 'lab', '--image', 'ceos:latest', '--output', str(output)]
            result = subprocess.run(command + ['--mgmt-subnet', '10.40.0.0/23'], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(clab.read_yaml(output)['mgmt']['ipv4-subnet'], '10.40.0.0/23')
            output.unlink()
            result = subprocess.run(command + ['--mgmt-subnet', '10.40.0.1/23'], capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertFalse(output.exists())

    def test_generate_custom_nameservers_and_reject_invalid_values(self):
        with tempfile.TemporaryDirectory() as d:
            source = Path(d) / 'act.yml'
            source.write_text('# Generated by generate.sh\nnodes:\n  - a: {node_type: veos, serial_number: a}\nlinks: []\n')
            output = Path(d) / 'lab.yml'
            command = ['python3', str(ROOT / 'clab.py'), 'generate', str(source), '--name', 'lab', '--image', 'ceos:latest', '--output', str(output)]
            result = subprocess.run(command + ['--name-servers', '10.1.1.1', '10.1.1.2'], capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            exec_command = clab.read_yaml(output)['topology']['kinds']['arista_ceos']['exec'][0]
            self.assertIn('ip name-server vrf MGMT 10.1.1.1', exec_command)
            self.assertIn('ip name-server vrf MGMT 10.1.1.2', exec_command)
            self.assertNotIn('8.8.8.8', exec_command)
            output.unlink()
            result = subprocess.run(command + ['--name-servers', 'bad;command'], capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertFalse(output.exists())


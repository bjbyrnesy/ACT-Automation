    def test_member_leaf_sets_are_centered_beneath_connected_leaf_pairs(self):
        names = ["x-A-leaf1", "x-A-leaf2", "x-A-leaf3", "x-A-leaf4"] + [
            f"x-A-mleaf{i}" for i in range(1, 7)
        ]
        links = []
        for i in range(1, 7):
            pair = (1, 2) if i <= 5 else (3, 4)
            for parent in pair:
                links.append(
                    {
                        "connection": [
                            f"x-A-mleaf{i}:Ethernet{parent}",
                            f"x-A-leaf{parent}:Ethernet{i}",
                        ]
                    }
                )

def test_run_create_asks_sites_and_fabric_mode(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
):
    labels: list[str] = []
    responses = iter(
        [
            "demo",
            "",
            "2",  # sites
            "",  # use case (default datacenter)
            "l3ls",
            "",  # spines per site
            "",  # leaves per site
            "",  # max spines
            "",  # max leaves
            "0",  # max mleafs
            "n",  # leaf mlag
            "",  # spine mlag (spines==2)
            "",  # eos
        ]
    )

    def prompt_value(label: str, default: str | None = None) -> str:
        labels.append(label)
        return next(responses) or default or ""

    monkeypatch.setattr(create.sys.stdin, "isatty", lambda: True)
    monkeypatch.setattr(create, "prompt_value", prompt_value)

    output_path = create.run_create(tmp_path)
    text = output_path.read_text(encoding="utf-8")

    assert any(label.startswith("Number of sites") for label in labels)
    assert any(label.startswith("Fabric mode") for label in labels)
    assert any(label == "Spines per site" for label in labels)
    assert "demo-A-border1:" in text
    assert "demo-bb1:" in text
    assert "fabric_mode=l3ls" in text
    cached = create.load_config(tmp_path / ".config")
    assert cached["DC_COUNT"] == "2"
    assert cached["FABRIC_MODE"] == "l3ls"


def test_emit_includes_capacity_and_mesh_without_spare_links():
    spec = FabricSpec(
        hostname_prefix="demo",
        serial_prefix="demo",
        eos_version="4.35.4M",
        capacity=Capacity(
            fabric_mode=None,
            max_spines=4,
            max_leaves=8,
            max_mleafs_per_pair=2,
            spines=2,
            leaves=2,
        ),
        mlag_pairs=True,
        spine_mlag=False,
        member_leaf_pairs=[],
        member_leaves_per_pair=0,
    )
    text = emit_act_yaml(spec)
    assert "max_spines=4" in text
    assert "demo-spine1:" in text
    conns = parse_connections(text)
    # 2 spines * 2 leaves = 4 mesh + 2 MLAG peer links = 6
    assert len(conns) == 6
    # reserved leaf3 on spine must not appear
    assert not any(
        conn.a_port == 3 or conn.b_port == 3 for conn in conns if "spine" in conn.a_node
    )


